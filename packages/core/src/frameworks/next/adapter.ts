import { file, indent, json, renderImports } from "../../engine/code";
import { createModel } from "../../engine/model";
import type {
  CounterSpec,
  Ctx,
  FrameworkAdapter,
  ProjectModel,
} from "../../types";
import {
  aboutText,
  demoClasses,
  globalCss,
  type DemoClasses,
} from "../shared/demo";
import { jsxCounter, wrapProviders } from "../shared/jsx";

const localCounter: CounterSpec = {
  imports: [{ from: "react", named: ["useState"] }],
  setup: ["const [count, setCount] = useState(0);"],
  value: "count",
  increment: "() => setCount((n) => n + 1)",
  decrement: "() => setCount((n) => n - 1)",
};

const routes = [
  { path: "/", label: "Home" },
  { path: "/about", label: "About" },
];

/**
 * Next.js App Router, following `create-next-app --empty` (no src dir, `@/*` alias).
 * Pages are server components; the counter is a client component. Routing is file-based,
 * so routing modules are not offered.
 */
export const nextAdapter: FrameworkAdapter = {
  id: "next",
  name: "Next.js",
  kind: "meta",
  languages: ["js", "ts"],
  srcDir: "",
  publicEnv: (name) => {
    const key = `NEXT_PUBLIC_${name}`;
    return { key, read: `process.env.${key}` };
  },
  ignore: [".next", "out", "next-env.d.ts", "*.tsbuildinfo"],
  componentExt: (language) => (language === "ts" ? "tsx" : "jsx"),

  base(ctx) {
    const model = createModel();
    const { pkg } = model;
    pkg.dependencies.add("next").add("react").add("react-dom");
    pkg.scripts["dev"] = "next dev";
    pkg.scripts["build"] = "next build";
    pkg.scripts["start"] = "next start";
    if (ctx.isTs) {
      pkg.devDependencies
        .add("typescript")
        .add("@types/node")
        .add("@types/react")
        .add("@types/react-dom");
      // `next typegen` writes next-env.d.ts and the route types used by `LayoutProps`.
      pkg.scripts["typecheck"] = "next typegen && tsc --noEmit";
      model.files.set("tsconfig.json", json(tsconfig()));
      model.files.set(
        "next.config.ts",
        file([
          'import type { NextConfig } from "next";',
          "",
          "const nextConfig: NextConfig = {};",
          "",
          "export default nextConfig;",
        ]),
      );
    } else {
      model.files.set(
        "jsconfig.json",
        json({ compilerOptions: { paths: { "@/*": ["./*"] } } }),
      );
      model.files.set(
        "next.config.mjs",
        file([
          '/** @type {import("next").NextConfig} */',
          "const nextConfig = {};",
          "",
          "export default nextConfig;",
        ]),
      );
    }
    model.readme.stack.push(
      "Next.js (App Router)",
      "React 19",
      ...(ctx.isTs ? ["TypeScript"] : []),
    );
    return model;
  },

  render(model, ctx) {
    const cls = demoClasses(model);
    const x = ctx.ext.component;
    model.files.set("app/globals.css", globalCss(model));
    model.files.set(`app/layout.${x}`, layout(model, ctx, cls));
    model.files.set(`app/page.${x}`, homePage(ctx, cls));
    model.files.set(`app/about/page.${x}`, aboutPage(model, cls));
    model.files.set(
      `components/Counter.${x}`,
      // Hooks and onClick need a client component.
      `"use client";\n\n${jsxCounter(model.demo.counter ?? localCounter, cls, "className")}`,
    );
  },
};

function tsconfig() {
  return {
    compilerOptions: {
      target: "ES2017",
      lib: ["dom", "dom.iterable", "esnext"],
      allowJs: true,
      skipLibCheck: true,
      strict: true,
      noEmit: true,
      esModuleInterop: true,
      module: "esnext",
      moduleResolution: "bundler",
      resolveJsonModule: true,
      isolatedModules: true,
      jsx: "react-jsx",
      incremental: true,
      plugins: [{ name: "next" }],
      paths: { "@/*": ["./*"] },
    },
    include: [
      "next-env.d.ts",
      "**/*.ts",
      "**/*.tsx",
      ".next/types/**/*.ts",
      ".next/dev/types/**/*.ts",
      "**/*.mts",
    ],
    exclude: ["node_modules"],
  };
}

function layout(model: ProjectModel, ctx: Ctx, cls: DemoClasses): string {
  const links = routes.flatMap((r) => [
    `<Link className="${cls.link}" href="${r.path}">`,
    `  ${r.label}`,
    "</Link>",
  ]);
  const content = [
    `<main className="${cls.main}">`,
    `  <nav className="${cls.nav}">`,
    ...indent(links, 2),
    "  </nav>",
    "  {children}",
    "</main>",
  ];
  return file([
    ...renderImports([
      ...(ctx.isTs ? [{ from: "next", types: ["Metadata"] }] : []),
      { from: "next/link", default: "Link" },
      ...model.entry.providers.flatMap((p) => p.imports),
      { from: "./globals.css" },
    ]),
    "",
    `export const metadata${ctx.isTs ? ": Metadata" : ""} = {`,
    `  title: "${ctx.selection.name}",`,
    '  description: "Generated by StackForge",',
    "};",
    "",
    `export default function RootLayout({ children }${ctx.isTs ? ': LayoutProps<"/">' : ""}) {`,
    "  return (",
    '    <html lang="en">',
    "      <body>",
    ...indent(wrapProviders(model, content), 4),
    "      </body>",
    "    </html>",
    "  );",
    "}",
  ]);
}

function homePage(ctx: Ctx, cls: DemoClasses): string {
  return file([
    'import Counter from "@/components/Counter";',
    "",
    "export default function Home() {",
    "  return (",
    `    <section className="${cls.page}">`,
    `      <h1 className="${cls.title}">${ctx.selection.name}</h1>`,
    "      <Counter />",
    "    </section>",
    "  );",
    "}",
  ]);
}

function aboutPage(model: ProjectModel, cls: DemoClasses): string {
  return file([
    "export default function About() {",
    "  return (",
    `    <section className="${cls.page}">`,
    `      <h1 className="${cls.title}">About</h1>`,
    `      <p className="${cls.text}">${aboutText(model)}</p>`,
    "    </section>",
    "  );",
    "}",
  ]);
}
