import { file, indent, renderImports } from "../../engine/code";
import type { Ctx, ProjectModel, RouteSpec } from "../../types";
import { aboutText, type DemoClasses } from "./demo";
import type { ClassAttr } from "./jsx";
import { widgetElements, widgetImports } from "./widgets";

/**
 * TanStack Router file-based routes: `src/routes/` plus the route tree its Vite plugin
 * generates. The tree is written here exactly as the plugin prints it (single quotes, no
 * semicolons), so a TS project typechecks before the first build and the plugin leaves the
 * file unchanged; TanStack's docs say to commit it and keep it out of linters and formatters.
 */

/** Route file name: `index` for the home page, else the path without its slash. */
function fileName(route: RouteSpec): string {
  return route.page === "home" ? "index" : route.path.slice(1);
}

const pascal = (name: string) => name.charAt(0).toUpperCase() + name.slice(1);

export function routeTreeFile(ctx: Ctx): string {
  return `src/routeTree.gen.${ctx.isTs ? "ts" : "js"}`;
}

export function routeTree(
  routes: RouteSpec[],
  pkg: string,
  ts: boolean,
): string {
  const names = routes.map((route) => ({
    route,
    name: pascal(fileName(route)),
    file: fileName(route),
  }));
  const list = (render: (n: (typeof names)[number]) => string) =>
    names.map(render);
  const union = (key: (n: (typeof names)[number]) => string) =>
    names.map((n) => `'${key(n)}'`).join(" | ");
  const byPath = (indentBy: string) =>
    list((n) => `${indentBy}'${n.route.path}': typeof ${n.name}Route`);

  return file([
    "/* eslint-disable */",
    "",
    "// @ts-nocheck",
    "",
    "// noinspection JSUnusedGlobalSymbols",
    "",
    "// This file was automatically generated by TanStack Router.",
    "// You should NOT make any changes in this file as it will be overwritten.",
    "// Additionally, you should also exclude this file from your linter and/or formatter to prevent it from being checked or modified.",
    "",
    "import { Route as rootRouteImport } from './routes/__root'",
    ...list(
      (n) =>
        `import { Route as ${n.name}RouteImport } from './routes/${n.file}'`,
    ),
    "",
    ...names.flatMap((n) => [
      `const ${n.name}Route = ${n.name}RouteImport.update({`,
      `  id: '${n.route.path}',`,
      `  path: '${n.route.path}',`,
      "  getParentRoute: () => rootRouteImport,",
      ts ? "} as any)" : "})",
    ]),
    "",
    ...(ts
      ? [
          "export interface FileRoutesByFullPath {",
          ...byPath("  "),
          "}",
          "export interface FileRoutesByTo {",
          ...byPath("  "),
          "}",
          "export interface FileRoutesById {",
          "  __root__: typeof rootRouteImport",
          ...byPath("  "),
          "}",
          "export interface FileRouteTypes {",
          "  fileRoutesByFullPath: FileRoutesByFullPath",
          `  fullPaths: ${union((n) => n.route.path)}`,
          "  fileRoutesByTo: FileRoutesByTo",
          `  to: ${union((n) => n.route.path)}`,
          `  id: '__root__' | ${union((n) => n.route.path)}`,
          "  fileRoutesById: FileRoutesById",
          "}",
          "export interface RootRouteChildren {",
          ...list((n) => `  ${n.name}Route: typeof ${n.name}Route`),
          "}",
          "",
          `declare module '${pkg}' {`,
          "  interface FileRoutesByPath {",
          ...names.flatMap((n) => [
            `    '${n.route.path}': {`,
            `      id: '${n.route.path}'`,
            `      path: '${n.route.path}'`,
            `      fullPath: '${n.route.path}'`,
            `      preLoaderRoute: typeof ${n.name}RouteImport`,
            "      parentRoute: typeof rootRouteImport",
            "    }",
          ]),
          "  }",
          "}",
          "",
          "const rootRouteChildren: RootRouteChildren = {",
        ]
      : ["const rootRouteChildren = {"]),
    ...list((n) => `  ${n.name}Route: ${n.name}Route,`),
    "}",
    ...(ts
      ? [
          "export const routeTree = rootRouteImport",
          "  ._addFileChildren(rootRouteChildren)",
          "  ._addFileTypes<FileRouteTypes>()",
        ]
      : [
          "export const routeTree = rootRouteImport._addFileChildren(rootRouteChildren)",
        ]),
  ]);
}

/** `src/routes/` (root layout with nav, one file per route) and the route tree. */
export function writeFileRoutes(
  model: ProjectModel,
  ctx: Ctx,
  cls: DemoClasses,
  attr: ClassAttr,
  pkg: string,
): void {
  const x = ctx.ext.component;
  const links = model.routes.flatMap((route) => [
    `<Link ${attr}="${cls.link}" to="${route.path}"${route.page === "home" ? " activeOptions={{ exact: true }}" : ""}>`,
    `  ${route.label}`,
    "</Link>",
  ]);
  model.files.set(
    `src/routes/__root.${x}`,
    file([
      `import { createRootRoute, Link, Outlet } from "${pkg}";`,
      "",
      "export const Route = createRootRoute({",
      "  component: RootLayout,",
      "});",
      "",
      "function RootLayout() {",
      "  return (",
      `    <main ${attr}="${cls.main}">`,
      `      <nav ${attr}="${cls.nav}">`,
      ...indent(links, 4),
      "      </nav>",
      "      <Outlet />",
      "    </main>",
      "  );",
      "}",
    ]),
  );
  for (const route of model.routes) {
    const home = route.page === "home";
    model.files.set(
      `src/routes/${fileName(route)}.${x}`,
      file([
        `import { createFileRoute } from "${pkg}";`,
        ...(home
          ? renderImports([
              { from: "../components/Counter", default: "Counter" },
              ...widgetImports(model, "../components"),
            ])
          : []),
        "",
        `export const Route = createFileRoute("${route.path}")({`,
        `  component: ${route.component},`,
        "});",
        "",
        `function ${route.component}() {`,
        "  return (",
        `    <section ${attr}="${cls.page}">`,
        ...(home
          ? [
              `      <h1 ${attr}="${cls.title}">${ctx.selection.name}</h1>`,
              "      <Counter />",
              ...widgetElements(model, 3),
            ]
          : [
              `      <h1 ${attr}="${cls.title}">${route.label}</h1>`,
              `      <p ${attr}="${cls.text}">${aboutText(model)}</p>`,
            ]),
        "    </section>",
        "  );",
        "}",
      ]),
    );
  }
  model.files.set(routeTreeFile(ctx), routeTree(model.routes, pkg, ctx.isTs));
}
